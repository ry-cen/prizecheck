"""Generate catalog decision and reassignment types from the API contract."""
from pathlib import Path
import sys,json
root=Path(__file__).resolve().parents[1];sys.path.insert(0,str(root/'api'))
from app.main import app
schema=app.openapi()['components']['schemas']
def ts(value):
    if '$ref' in value:return value['$ref'].split('/')[-1]
    if 'anyOf' in value:return ' | '.join(ts(x) for x in value['anyOf'])
    if 'enum' in value:return ' | '.join(json.dumps(x) for x in value['enum'])
    if value.get('type')=='array':return ts(value['items'])+'[]'
    if value.get('type')=='object':return 'Record<string, unknown>'
    return {'string':'string','integer':'number','null':'null','boolean':'boolean'}[value['type']]
lines=['// Generated by scripts/generate_reconciliation_client.py. Do not edit.',"import { HoldingError } from './holdings_generated';"]
for name in ('CatalogReviewView','ReviewEditionView','EditionReplacementInput','CatalogDecision','ReassignHolding','ReassignResult','ReplacementView'):
    d=schema[name];fields=[f"{key}{'' if key in d.get('required',[]) else '?'}: {ts(value)}" for key,value in d['properties'].items()]
    lines.append(f"export type {name} = {{ {'; '.join(fields)} }};")
lines.append('''
async function request<T>(path: string,body?: object): Promise<T> {
  const response=await fetch(path,{method:body?'POST':'GET',credentials:'same-origin',headers:body?{'content-type':'application/json'}:undefined,body:body?JSON.stringify(body):undefined});
  if(!response.ok){const result=await response.json().catch(()=>({}));throw new HoldingError(response.status,result?.detail?.code??'CATALOG_REVIEW_UNAVAILABLE');}
  return response.json() as Promise<T>;
}
export const getCatalogReviews=()=>request<CatalogReviewView[]>('/api/admin/catalog-reviews');
export const getReviewEditions=(id: string)=>request<ReviewEditionView[]>(`/api/admin/catalog-reviews/${encodeURIComponent(id)}/editions`);
export const decideCatalogReview=(id: string,body: CatalogDecision)=>request<CatalogReviewView>(`/api/admin/catalog-reviews/${encodeURIComponent(id)}/decision`,body);
export const getEditionReplacements=()=>request<ReplacementView[]>('/api/catalog/edition-replacements');
export const reassignHolding=(body: ReassignHolding)=>request<ReassignResult>('/api/holdings/reassign',body);
export const requestReviewCode=(reviewId: string,action:'confirm_source'|'resolve_catalog')=>request<{message:string}>('/auth/approval-code',{reviewId,action});
''')
content='\n'.join(lines)+'\n';target=root/'web/src/reconciliation_generated.ts'
if '--check' in sys.argv:
    if not target.exists() or target.read_text()!=content:raise SystemExit('Reconciliation client stale')
else:target.write_text(content)
