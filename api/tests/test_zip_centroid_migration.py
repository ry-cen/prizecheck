"""Migration 146 and scripts/build_zip_centroids.py (Trading #297).

The parsing checks run on tiny in-memory files, with no network and no database. The migration checks read the
generated file and apply it to a disposable database, then again with nothing changed.
"""
import importlib.util
import re
from pathlib import Path

import psycopg
import pytest
from psycopg.rows import dict_row

from test_catalog_references import migrate
from test_trade_migrations import run_again, scratch  # noqa: F401

ROOT = Path(__file__).resolve().parents[2]
MIGRATION = ROOT / 'migrations' / '146_zip_centroids.sql'

spec = importlib.util.spec_from_file_location('build_zip_centroids', ROOT / 'scripts' / 'build_zip_centroids.py')
build = importlib.util.module_from_spec(spec)
spec.loader.exec_module(build)

CENSUS = ('GEOID|GEOIDFQ|ALAND|AWATER|ALAND_SQMI|AWATER_SQMI|INTPTLAT|INTPTLONG   \n'
          '00601|x|1|1|1|1|18.180621|-66.749931\n'
          '00602|x|1|1|1|1|40.12345|-100.12345\n'
          '00603|x|1|1|1|1|40.12355|-100.5\n')


def geonames(*rows):
    """GeoNames lines: (zip, lat, lon, accuracy) in the 12-column layout."""
    return '\n'.join('\t'.join(['US', z, 'Town', 'State', 'ST', 'County', '001', '', '', lat, lon, acc])
                     for z, lat, lon, acc in rows) + '\n'


def test_the_build_takes_census_first_and_drops_estimated_geonames_rows(capsys):
    census = build.census_rows(CENSUS)
    assert set(census) == {'00601', '00602', '00603'}
    found, counts = build.geonames_rows(geonames(
        ('00601', '1.0', '2.0', '6'),  # Census has it too
        ('00700', '10.0', '20.0', '1'),  # estimated: dropped
        ('00800', '30.0', '40.0', '4'),  # duplicate, lower accuracy
        ('00800', '31.0', '41.0', '6'),  # duplicate, kept
        ('1234', '5.0', '6.0', '4'),  # 4 digits: dropped
        ('00900', '7.0', '8.0', '')))  # empty accuracy counts as 0
    assert counts == {'read': 6, 'dropped_accuracy_1': 1, 'dropped_not_5_digits': 1, 'duplicates': 1}
    assert str(found['00800'][0]) == '31.0'
    rows = build.merge(census, found)
    assert rows == [
        ('00601', '18.1806', '-66.7499', 'census'),
        ('00602', '40.1234', '-100.1234', 'census'),
        ('00603', '40.1236', '-100.5000', 'census'),
        ('00800', '31.0000', '41.0000', 'geonames'),
        ('00900', '7.0000', '8.0000', 'geonames')]
    eleven = '\t'.join(['US', '00700', 'Town', 'State', 'ST', 'County', '001', '', '', '1.0', '2.0']) + '\n'
    for text, message in ((geonames(('00700', 'NaN', '2.0', '4')), 'out of range'),
                          (geonames(('00700', '95.0', '2.0', '4')), 'out of range'),
                          (geonames(('00700', '1.0', '2.0', 'x')), "accuracy 'x' is not an integer"),
                          (eleven, 'has 11 columns, expected 12')):
        with pytest.raises(SystemExit) as raised:
            build.geonames_rows(text)
        assert raised.value.code == 1
        assert message in capsys.readouterr().err
    with pytest.raises(SystemExit):
        build.census_rows(CENSUS + '00601|x|1|1|1|1|1.0|2.0\n')
    with pytest.raises(SystemExit):
        build.census_rows(CENSUS.replace('00602', '0060'))


def header_counts():
    match = re.search(r'^-- Rows: census (\d+), geonames (\d+) \(codes the Census file lacks\), total (\d+)$',
                      MIGRATION.read_text(), re.MULTILINE)
    assert match
    return tuple(int(n) for n in match.groups())


def test_migration_146_loads_every_zip_once_and_runs_again(scratch):  # noqa: F811
    migrate(scratch)
    census, geo, total = header_counts()

    def counts():
        with psycopg.connect(scratch, row_factory=dict_row) as conn:
            by_source = {r['source']: r['n'] for r in conn.execute(
                'SELECT source, count(*) AS n FROM zip_centroid GROUP BY source')}
            bad = conn.execute("""SELECT count(*) AS n FROM zip_centroid
              WHERE lat NOT BETWEEN -90 AND 90 OR lon NOT BETWEEN -180 AND 180""").fetchone()['n']
        return by_source, bad

    by_source, bad = counts()
    assert by_source == {'census': census, 'geonames': geo}
    assert sum(by_source.values()) == total
    assert bad == 0
    run_again(scratch, '146_zip_centroids.sql')
    assert counts() == (by_source, 0)


def test_the_zip_data_is_generated_not_hand_edited():
    text = MIGRATION.read_text(encoding='ascii')
    assert build.CENSUS_URL in text and build.GEONAMES_URL in text
    assert len(re.findall(r'sha256 [0-9a-f]{64}', text)) == 2
    assert '-- GENERATED by scripts/build_zip_centroids.py' in text
    assert max(len(line) for line in text.split('\n')) <= 200
