-- The printed set code of a TCGdex set (WP-C1, shared-core refactor). Holds exactly the rows of api/app/set_codes.tsv; a
-- later NNN_set_codes.sql (scripts/set_code_migration.py) replaces the rows and leaves the table and view alone. Catalog
-- import and refresh never touch it: a set without a row shows its TCGdex set ID, as set_codes.code_for does.
CREATE TABLE catalog_set_code (
 set_id text PRIMARY KEY CHECK (length(set_id) BETWEEN 1 AND 80),
 code text NOT NULL CHECK (code ~ '^[A-Z0-9]{2,4}$')
);
-- The one place the fallback is written: set_codes.code_for(coalesce(pd.set_id, '')) for every Printing, one row each.
CREATE VIEW catalog_printing_set_code AS
SELECT p.id AS printing_id, coalesce(sc.code, pd.set_id, '') AS set_code
  FROM catalog_printing p
  LEFT JOIN catalog_printing_display pd ON pd.printing_id = p.id
  LEFT JOIN catalog_set_code sc ON sc.set_id = pd.set_id;
DELETE FROM catalog_set_code;
